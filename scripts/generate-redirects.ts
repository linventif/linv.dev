import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

type Shortcut = { path: string; site: string };
type Subdomain = { site: string; redirect?: { target: string; preservePath: boolean } };
export type RedirectFiles = {
  pages: string;
  nginxShortcuts: string;
  nginxSubdomains: string;
  cloudflareCsv: string;
};

const legacyPaths = ['/creations', '/docs', '/colors', '/social', '/terms'];
const pathPattern = /^\/[a-z0-9-]+(?:\.[a-z0-9-]+)?$/;
const subdomainPattern = /^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+linv\.dev$/;

function object(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

export function validateHttpsUrl(value: unknown): URL {
  if (typeof value !== 'string' || /[\s\u0000-\u001f\u007f]/u.test(value)) {
    throw new Error('Une URL HTTPS sans espaces ni caractères de contrôle est requise.');
  }
  let url: URL;
  try { url = new URL(value); } catch { throw new Error('URL invalide.'); }
  if (url.protocol !== 'https:' || url.username || url.password || url.port || /[\\$]/.test(value)) {
    throw new Error('Une URL HTTPS sans identifiants ni port personnalisé est requise.');
  }
  return url;
}

function shortcutsFrom(value: unknown): Shortcut[] {
  if (!Array.isArray(value)) throw new Error('shortcuts.json doit contenir un tableau.');
  const paths = new Set(legacyPaths);
  return value.map(entry => {
    if (!object(entry) || typeof entry.path !== 'string' || !pathPattern.test(entry.path)) {
      throw new Error('Chemin de raccourci invalide.');
    }
    if (paths.has(entry.path)) throw new Error(`Chemin de raccourci dupliqué ou réservé : ${entry.path}.`);
    paths.add(entry.path);
    return { path: entry.path, site: validateHttpsUrl(entry.site).href };
  });
}

function subdomainsFrom(value: unknown): Subdomain[] {
  if (!Array.isArray(value)) throw new Error('subdomains.json doit contenir un tableau.');
  const hosts = new Set<string>();
  return value.map(entry => {
    if (!object(entry)) throw new Error('Sous-domaine invalide.');
    const site = validateHttpsUrl(entry.site);
    if (!subdomainPattern.test(site.hostname) || site.pathname !== '/' || site.search || site.hash) {
      throw new Error('Un sous-domaine exact de linv.dev, sans chemin, est requis.');
    }
    if (hosts.has(site.hostname)) throw new Error(`Sous-domaine dupliqué : ${site.hostname}.`);
    hosts.add(site.hostname);
    if (entry.redirect === undefined) return { site: site.href };
    if (!object(entry.redirect) || typeof entry.redirect.preservePath !== 'boolean') {
      throw new Error(`Redirection invalide pour ${site.hostname}.`);
    }
    const target = validateHttpsUrl(entry.redirect.target);
    if (entry.redirect.preservePath && (target.search || target.hash)) {
      throw new Error('Une redirection conservant le chemin ne peut pas avoir de query ou fragment cible.');
    }
    if (target.hostname === site.hostname) throw new Error(`Redirection vers le même hôte : ${site.hostname}.`);
    return { site: site.href, redirect: { target: target.href, preservePath: entry.redirect.preservePath } };
  });
}

function nginxQuote(value: string): string {
  return value.replace(/[\\"$]/g, character => `\\${character}`);
}

function csvCell(value: string): string {
  return /[",\r\n]/.test(value) ? `"${value.replaceAll('"', '""')}"` : value;
}

/** Generate explicit rules only; unrelated Host headers never get a generated server. */
export function generateRedirects(rawShortcuts: unknown, rawSubdomains: unknown): RedirectFiles {
  const shortcuts = shortcutsFrom(rawShortcuts);
  const subdomains = subdomainsFrom(rawSubdomains);
  const comment = '# Generated by scripts/generate-redirects.ts. Do not edit manually.\n';
  const pagesRules: string[] = [];
  const nginxRules: string[] = [];
  for (const shortcut of shortcuts) {
    for (const path of [shortcut.path, `${shortcut.path}/`]) {
      pagesRules.push(`${path} ${shortcut.site} 302`);
      nginxRules.push(`location = ${path} {\n    return 302 "${nginxQuote(shortcut.site)}";\n}`);
    }
  }
  for (const path of legacyPaths) {
    pagesRules.push(`${path} /#projets 302`, `${path}/ /#projets 302`);
  }
  const servers: string[] = [];
  const csv: string[] = [];
  for (const subdomain of subdomains) {
    if (!subdomain.redirect) continue;
    const host = new URL(subdomain.site).hostname;
    const { target, preservePath } = subdomain.redirect;
    // $request_uri preserves both the original encoded path and query string.
    const nginxTarget = preservePath
      ? `${nginxQuote(target.replace(/\/$/, ''))}$request_uri`
      : nginxQuote(target);
    servers.push(`server {\n    listen 80;\n    listen [::]:80;\n    server_name ${host};\n    return 302 "${nginxTarget}";\n}`);
    for (const scheme of ['https', 'http']) {
      csv.push([`${scheme}://${host}/`, target, '302', preservePath ? 'TRUE' : 'FALSE', 'FALSE', 'TRUE', preservePath ? 'TRUE' : 'FALSE'].map(csvCell).join(','));
    }
  }
  return {
    pages: `${comment}${pagesRules.join('\n')}\n`,
    nginxShortcuts: `${comment}${nginxRules.join('\n\n')}\n`,
    nginxSubdomains: `${comment}${servers.join('\n\n')}\n`,
    // Cloudflare Bulk Redirects CSV must not contain a header or comments.
    cloudflareCsv: csv.length ? `${csv.join('\n')}\n` : '',
  };
}

async function run(): Promise<void> {
  const base = new URL('../', import.meta.url);
  const [shortcuts, subdomains] = await Promise.all([
    readFile(new URL('src/data/shortcuts.json', base), 'utf8').then(JSON.parse),
    readFile(new URL('src/data/subdomains.json', base), 'utf8').then(JSON.parse),
  ]);
  const files = generateRedirects(shortcuts, subdomains);
  await mkdir(new URL('public/', base), { recursive: true });
  await mkdir(new URL('cloudflare/', base), { recursive: true });
  await Promise.all([
    writeFile(new URL('public/_redirects', base), files.pages),
    writeFile(new URL('nginx-shortcuts.conf', base), files.nginxShortcuts),
    writeFile(new URL('nginx-subdomains.conf', base), files.nginxSubdomains),
    writeFile(new URL('cloudflare/subdomain-redirects.csv', base), files.cloudflareCsv),
  ]);
  console.log('Redirections Pages, Nginx et CSV Cloudflare générés.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  run().catch(error => {
    console.error(error instanceof Error ? error.message : 'Échec de la génération des redirections.');
    process.exitCode = 1;
  });
}
